"use client";

import { useEffect, useMemo, useRef } from "react";
import { useFrame } from "@react-three/fiber";
import { useGLTF } from "@react-three/drei";
import {
  AdditiveBlending,
  BackSide,
  Color,
  DoubleSide,
  MeshBasicMaterial,
  Plane,
  PointsMaterial,
  Vector3,
  type Mesh,
  type MeshPhysicalMaterial,
  type Points,
} from "three";
import { TOOTH_MODEL_URL } from "@/config/models";
import { type QualityTier } from "@/lib/three";
import { scanDepth, scrollState } from "@/lib/scroll-state";

// Meshopt-compressed GLB — decoder is bundled, no Draco / CDN fetch.
const USE_DRACO = false;
const USE_MESHOPT = true;

/**
 * World-space scan planes, shared with <ScanRing>. Three.js keeps fragments on the positive side:
 * `below` keeps the solid tooth under the scan, `above` keeps the scanned point cloud over it.
 * The plane is tipped towards the camera by SCAN_TILT so you look down into the cross-section
 * (a level cut would be seen edge-on).
 */
export const SCAN_TILT = 0.42; // radians
export const SCAN_NORMAL = new Vector3(0, Math.cos(SCAN_TILT), Math.sin(SCAN_TILT)); // faces up + towards camera
export const scanPlanes = {
  below: new Plane(SCAN_NORMAL.clone().negate(), 99),
  above: new Plane(SCAN_NORMAL.clone(), -99),
};

/** World-space vertical range the scan sweeps (cusp tips → mid-root), set for the rig's resting pose. */
export const SCAN_TOP = 1.34;
export const SCAN_BOTTOM = -0.1;

type ToothModelProps = { quality: QualityTier };

/**
 * Molar GLB (public/models/tooth.glb, generated by `npm run model:tooth`).
 * - Enamel / cementum: MeshPhysicalMaterial from the GLB (clearcoat, IOR 1.62, zone map, baked AO).
 * - Scan cut: back faces drawn flat in Mist read as a solid cross-section; the pulp glows inside.
 * - Above the cut, the same vertices render as a point cloud — the digitised half of the scan.
 */
export function ToothModel({ quality }: ToothModelProps) {
  const { nodes } = useGLTF(TOOTH_MODEL_URL, USE_DRACO, USE_MESHOPT);
  const tooth = nodes.Tooth as Mesh;
  const pulp = nodes.Pulp as Mesh;

  const cap = useRef<Mesh>(null);
  const pulpRef = useRef<Mesh>(null);
  const cloud = useRef<Points>(null);

  const materials = useMemo(() => {
    const enamel = (tooth.material as MeshPhysicalMaterial).clone();
    enamel.envMapIntensity = 1.1;
    enamel.specularIntensity = 1;
    enamel.clearcoatRoughness = 0.06;
    enamel.clippingPlanes = [scanPlanes.below];

    const section = new MeshBasicMaterial({ color: new Color("#d6ecff"), side: BackSide, clippingPlanes: [scanPlanes.below] });
    const pulpMat = new MeshBasicMaterial({ color: new Color("#38bdf8"), side: DoubleSide, clippingPlanes: [scanPlanes.below], toneMapped: false });
    const points = new PointsMaterial({
      color: new Color("#a7ddff"),
      size: quality === "high" ? 0.011 : 0.016,
      sizeAttenuation: true,
      transparent: true,
      opacity: 0.85,
      depthWrite: false,
      blending: AdditiveBlending,
      clippingPlanes: [scanPlanes.above],
      toneMapped: false,
    });
    return { enamel, section, pulpMat, points };
  }, [tooth, quality]);

  useEffect(() => () => Object.values(materials).forEach((m) => m.dispose()), [materials]);

  // The cut-only layers cost nothing until the scan is actually running.
  useFrame(() => {
    const scanning = scanDepth(scrollState.hero.scan) > 0.002;
    if (cap.current) cap.current.visible = scanning;
    if (pulpRef.current) pulpRef.current.visible = scanning;
    if (cloud.current) cloud.current.visible = scanning;
  });

  return (
    <group position={tooth.position} quaternion={tooth.quaternion} scale={tooth.scale}>
      <mesh geometry={tooth.geometry} material={materials.enamel} />
      <mesh ref={cap} geometry={tooth.geometry} material={materials.section} visible={false} />
      <points ref={cloud} geometry={tooth.geometry} material={materials.points} visible={false} />
      <mesh
        ref={pulpRef}
        geometry={pulp.geometry}
        material={materials.pulpMat}
        // The pulp node carries its own dequantisation transform; express it relative to the tooth's.
        position={pulp.position.clone().sub(tooth.position).divide(tooth.scale)}
        scale={pulp.scale.clone().divide(tooth.scale)}
        visible={false}
      />
    </group>
  );
}

useGLTF.preload(TOOTH_MODEL_URL, USE_DRACO, USE_MESHOPT);
